//! Extents the kernel stored through encoded writes must read back as
//! the kernel wrote them (#556).
//!
//! Every other compressed fixture was compressed by the kernel itself, on
//! a compressing mount. `btrfs receive --compressed-data` takes another
//! path: the send stream carries extents that are already compressed, and
//! receive hands them to the kernel's encoded-write ioctl, which stores
//! them as they are. The receiving volume here is mounted WITHOUT a
//! compression option, so every compressed extent on it arrived that way
//! and none was compressed on the spot.
//!
//! The guest builds it: files written on a compressing mount (zstd for
//! the mount, zlib and lzo per file through the compression property),
//! sent from a read-only snapshot with `btrfs send --compressed-data`, and
//! received onto a fresh volume. The manifest of sizes and SHA-256 per
//! file is taken by the kernel's own driver on a read-only mount of the
//! received volume, and the builder fails unless `dump-tree` of that
//! volume names every algorithm, so a receive that silently fell back to
//! decompressing cannot produce this fixture.
//!
//! The fixtures are gitignored and generated by `chore fixtures`. Nothing
//! here skips: a missing image fails, naming the task that builds it.

mod cli_support;

use cli_support::*;
use fs_btrfs::Filesystem;
use fs_btrfs_test_support::{assert_btrfs_check_clean, fixture, sha256_hex};
use fs_core::FileDevice;
use std::sync::Arc;

const IMAGE: &str = "encoded/btrfs-encoded.img";
const MANIFEST: &str = "encoded/btrfs-encoded.manifest";
const RECORD: &str = "encoded/btrfs-encoded.compression";

/// The algorithms the builder wrote the sent files with.
const ALGORITHMS: &[&str] = &["zstd", "zlib", "lzo"];

/// One manifest line: what the kernel says a received file holds.
struct Expected {
    path: String,
    size: u64,
    sha256: String,
}

fn manifest() -> Vec<Expected> {
    let text = std::fs::read_to_string(fixture(MANIFEST)).expect("read the manifest");
    let expected: Vec<Expected> = text
        .lines()
        .filter(|l| !l.starts_with('#') && !l.is_empty())
        .map(|l| {
            let mut f = l.split('\t');
            let mut field = |name: &str| {
                f.next()
                    .unwrap_or_else(|| panic!("manifest line {l:?} has no {name}"))
                    .to_string()
            };
            Expected {
                path: field("path"),
                size: field("size")
                    .parse()
                    .unwrap_or_else(|e| panic!("manifest line {l:?}: size: {e}")),
                sha256: field("sha256"),
            }
        })
        .collect();
    assert!(!expected.is_empty(), "{MANIFEST} lists no files");
    expected
}

/// Every received file reads back byte for byte, judged by the hash the
/// kernel computed for it after the receive.
#[test]
fn received_files_match_what_the_kernel_recorded() {
    let expected = manifest();
    let dev = FileDevice::open(fixture(IMAGE)).expect("open the received volume");
    let fs = Filesystem::mount(Arc::new(dev)).expect("mount the received volume");

    for want in &expected {
        // The received files sit in the `sent` subvolume, which the path
        // crosses into.
        let target = fs
            .resolve_path(&want.path)
            .unwrap_or_else(|e| panic!("{} not found: {e}", want.path));
        let got = target
            .fs(&fs)
            .read_file(target.inode.ino)
            .unwrap_or_else(|e| panic!("{} failed to read: {e}", want.path));
        assert_eq!(
            got.len() as u64,
            want.size,
            "{} is {} bytes, the kernel says {}",
            want.path,
            got.len(),
            want.size
        );
        assert_eq!(
            sha256_hex(&got),
            want.sha256,
            "{} reads as different bytes than the kernel recorded",
            want.path
        );
    }
    eprintln!("{} received files match", expected.len());
}

/// The received volume really holds compressed extents of every
/// algorithm, and a plain one beside them.
///
/// The builder already refuses a volume without them; this keeps a
/// rebuilt fixture from quietly losing the coverage the suite above
/// claims.
#[test]
fn the_received_extents_are_compressed() {
    let path = fixture(RECORD);
    let text = std::fs::read_to_string(&path).expect("read the compression record");
    for algo in ALGORITHMS {
        assert!(
            text.contains(&format!("({algo})")),
            "nothing on the received volume is {algo}-compressed, so no encoded \
             {algo} write is read. dump-tree found:\n{text}"
        );
    }
    assert!(
        text.contains("(none)"),
        "every received extent is compressed, so nothing checks the plain path:\n{text}"
    );
}

/// The reference checker calls the received volume clean, and so does
/// this crate's.
#[test]
fn the_received_volume_is_clean_to_both_checkers() {
    let image = scratch_dir("encoded-clean").join("btrfs-encoded.img");
    std::fs::copy(fixture(IMAGE), &image).expect("copy the received volume");
    assert_btrfs_check_clean(&image, "encoded");

    let out = tool("fsck.btrfs")
        .arg("--text")
        .arg(&image)
        .output()
        .expect("spawn fsck.btrfs");
    assert_eq!(
        out.status.code(),
        Some(0),
        "fsck.btrfs finds fault with a volume btrfs check calls clean:\n{}{}",
        stdout(&out),
        stderr(&out)
    );
}
